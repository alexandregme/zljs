/**
 * Semantic colors for action-oriented components (Button, Heading, etc.)
 */
export type SemanticColor =
  "primary" | "success" | "danger" | "warning" | "info" | "muted" | "none";

/**
 * Literal colors for data visualization components (StatsCard, etc.)
 */
export type DataColor = "blue" | "red" | "yellow" | "green" | "gray" | "orange";

/**
 * Extra colors with no meaning of their own, to tell categories apart (Tag)
 */
export type AuxiliaryColor = "orange" | "pink" | "purple";
